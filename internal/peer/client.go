// BroadcastIntent sends an intent notification to this peer. Errors are
// intentionally ignored by callers (fire-and-forget).
func (pc *PeerClient) BroadcastIntent(msg IntentMessage) error {
	body, _ := json.Marshal(msg)
	req, err := pc.newRequest(http.MethodPost, "/api/v1/intents", bytes.NewReader(body))
	if err != nil {
		return err
	}
	req.Header.Set("Content-Type", "application/json")
	resp, err := pc.httpCli.Do(req)
	if err != nil {
		return err
	}
	resp.Body.Close()
	return nil
}

// Name returns the configured peer name.
func (pc *PeerClient) Name() string { return pc.cfg.Name }

// newRequest creates a request with the peer's bearer token pre-applied.
func (pc *PeerClient) newRequest(method, path string, body *bytes.Reader) (*http.Request, error) {
	var req *http.Request
	var err error
	if body != nil {
		req, err = http.NewRequest(method, pc.cfg.URL+path, body)
	} else {
		req, err = http.NewRequest(method, pc.cfg.URL+path, nil)
	}
	if err != nil {
		return nil, err
	}
	if pc.cfg.Token != "" {
		req.Header.Set("Authorization", "Bearer "+pc.cfg.Token)
	}
	return req, nil
}
