// TestSummarize_DeterministicSummaryTestHelper verifies that Summarize returns
// a deterministic summary for test helper functions without calling the LLM.
func TestSummarize_DeterministicSummaryTestHelper(t *testing.T) {
	// No LLM call should happen, so a broken mock is fine
	mock := llm.NewMockClient(`{invalid json}`)
	st := newTestStore(t)
	ing := New(mock, st, 3*time.Second)

	resp, err := ing.Summarize(context.Background(), Request{
		ProjectID: "test-project",
		NodeID:    "node:test:TestX",
		NodeName:  "TestX",
		NodeType:  "function",
		Package:   "somepkg_test",
		Code:      "func TestX(t *testing.T) { }",
	})
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if resp.Summary == "" {
		t.Error("expected deterministic summary for test helper")
	}
	if len(resp.Tags) == 0 {
		t.Error("expected tags for test helper")
	}
}

