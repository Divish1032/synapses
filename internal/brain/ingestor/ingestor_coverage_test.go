// TestNew_DefaultTimeout verifies that New() sets a default timeout when
// timeout <= 0 is provided. This exercises the timeout initialization path.
func TestNew_DefaultTimeout(t *testing.T) {
	mock := llm.NewMockClient("")
	st := newTestStore(t)

	// Create ingestor with zero timeout
	ing := New(mock, st, 0)
	if ing.timeout <= 0 {
		t.Errorf("expected default timeout to be set, got %v", ing.timeout)
	}
	if ing.timeout != 3*time.Second {
		t.Errorf("expected default timeout of 3s, got %v", ing.timeout)
	}
}

