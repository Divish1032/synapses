// TestSummarize_StoreError verifies behavior when the store fails to persist
// a summary (though in practice store.SaveSummary rarely fails).
func TestSummarize_StoreError(t *testing.T) {
	// Create a store that will fail operations
	mock := llm.NewMockClient(`{"summary": "Test summary"}`)
	dir := t.TempDir()
	stPath := filepath.Join(dir, "brain.sqlite")

	st, err := store.Open(stPath)
	if err != nil {
		t.Fatalf("open store: %v", err)
	}
	t.Cleanup(func() { st.Close() })

	ing := New(mock, st, 3*time.Second)

	// Close the store to cause subsequent operations to fail
	st.Close()

	// Summarize should now fail because the store is closed
	_, err = ing.Summarize(context.Background(), Request{
		ProjectID: "test-project",
		NodeID:    "node:x",
		NodeName:  "X",
		Code:      "func X() {}",
	})
	if err == nil {
		t.Error("expected error when store is closed, got nil")
	}
}

// TestLooksLikeCode_EdgeCases tests the looksLikeCode edge case detection.
func TestLooksLikeCode_EdgeCases(t *testing.T) {
	testCases := []struct {
		name     string
		code     string
		expected bool
	}{
		{"empty", "", false},
		{"go_shortdecl", "x := 1", true},
		{"comment_only", "// comment", false},
		{"go_funcdef", "func f() {}", true},
		{"assignment", "x = 5", false},
		{"python_def", "def foo(x):", true},
		{"js_arrow", "x => x + 1", false},
		{"js_arrow_body", "() => {}", true},
		{"go_struct", "struct {}", false},
		{"go_struct_with_space", " struct {", true},
		{"go_interface", "interface {}", true},
		{"plain_prose", "This is just some plain text", false},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			result := looksLikeCode(tc.code)
			if result != tc.expected {
				t.Errorf("looksLikeCode(%q) = %v, expected %v", tc.code, result, tc.expected)
			}
		})
	}
}

// TestParseSummary_EdgeCases tests the parseSummary edge case paths.
func TestParseSummary_EdgeCases(t *testing.T) {
	testCases := []struct {
		name        string
		input       string
		expectError bool
		checkResult func(t *testing.T, summary string, tags []string)
	}{
		{
			"json_valid",
			`{"summary": "Test"}`,
			false,
			func(t *testing.T, summary string, tags []string) {
				if summary != "Test" {
					t.Errorf("expected 'Test', got %q", summary)
				}
			},
		},
		{
			"plain_text",
			`Simple text response`,
			false,
			func(t *testing.T, summary string, tags []string) {
				if summary != "Simple text response" {
					t.Errorf("expected plain text, got %q", summary)
				}
			},
		},
		{
			"empty_response",
			"",
			true,
			func(t *testing.T, summary string, tags []string) {
				if summary != "" {
					t.Errorf("expected empty on error, got %q", summary)
				}
			},
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			summary, tags, err := parseSummary(tc.input)
			if tc.expectError && err == nil {
				t.Errorf("expected error, got nil")
			}
			if !tc.expectError && err != nil {
				t.Errorf("unexpected error: %v", err)
			}
			tc.checkResult(t, summary, tags)
		})
	}
}
