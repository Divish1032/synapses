// ── Write + ContextFilePath ───────────────────────────────────────────────────

func TestWrite_CreatesFileAndContent(t *testing.T) {
	// Override HOME so we don't pollute the real ~/.synapses/context/.
	tmp := t.TempDir()
	t.Setenv("HOME", tmp)

	repoRoot := "/tmp/test-project"
	if err := Write(repoRoot, nil, nil); err != nil {
		t.Fatalf("Write failed: %v", err)
	}

	path, err := ContextFilePath(repoRoot)
	if err != nil {
		t.Fatalf("ContextFilePath failed: %v", err)
	}

	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("file not found at %s: %v", path, err)
	}
	if !strings.Contains(string(data), "Auto-generated by Synapses daemon") {
		t.Error("file missing expected content")
	}
}

func TestWrite_AtomicNoPanicOnDoubleWrite(t *testing.T) {
	tmp := t.TempDir()
	t.Setenv("HOME", tmp)

	repoRoot := "/tmp/test-project-atomic"
	for i := 0; i < 3; i++ {
		if err := Write(repoRoot, nil, nil); err != nil {
			t.Fatalf("Write #%d failed: %v", i, err)
		}
	}
}

func TestContextFilePath_IsInsideSynapsesContext(t *testing.T) {
	tmp := t.TempDir()
	t.Setenv("HOME", tmp)

	path, err := ContextFilePath("/some/project")
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	expected := filepath.Join(tmp, ".synapses", "context")
	if !strings.HasPrefix(path, expected) {
		t.Errorf("expected path under %s, got %s", expected, path)
	}
	if !strings.HasSuffix(path, ".md") {
		t.Errorf("expected .md suffix, got %s", path)
	}
}

