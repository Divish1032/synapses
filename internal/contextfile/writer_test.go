// ── fnvHash ───────────────────────────────────────────────────────────────────

func TestFnvHash_Deterministic(t *testing.T) {
	h1 := fnvHash("/home/user/myproject")
	h2 := fnvHash("/home/user/myproject")
	if h1 != h2 {
		t.Errorf("fnvHash not deterministic: %q != %q", h1, h2)
	}
}

func TestFnvHash_DifferentPaths(t *testing.T) {
	h1 := fnvHash("/home/user/projectA")
	h2 := fnvHash("/home/user/projectB")
	if h1 == h2 {
		t.Errorf("fnvHash collision for different paths: both = %q", h1)
	}
}

func TestFnvHash_Format(t *testing.T) {
	h := fnvHash("/any/path")
	if len(h) != 8 {
		t.Errorf("expected 8-char hex hash, got %q (len %d)", h, len(h))
	}
	for _, c := range h {
		if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f')) {
			t.Errorf("non-hex char %q in hash %q", c, h)
		}
	}
}

// ── filterPending ─────────────────────────────────────────────────────────────

func TestFilterPending_KeepsPendingAndInProgress(t *testing.T) {
	tasks := []store.Task{
		{ID: "1", Status: "pending"},
		{ID: "2", Status: "in_progress"},
		{ID: "3", Status: "done"},
		{ID: "4", Status: "cancelled"},
	}
	got := filterPending(tasks)
	if len(got) != 2 {
		t.Fatalf("expected 2 tasks, got %d", len(got))
	}
	if got[0].ID != "1" || got[1].ID != "2" {
		t.Errorf("unexpected tasks: %v", got)
	}
}

